function read(record: Record<string, string>, key: string, where: string): string {
  const value = record[key];
  if (value === undefined) throw new Error(`${where} has no ${key}`);
  return value;
}

/** Every source colour is composited over the surface it would sit on, because preman's are solid. */
function opaque(value: string, base: Rgb): Rgb {
  return flatten(parseColor(value), base);
}

/**
 * Push a colour away from `surfaces` until the worst ratio clears `target`.
 *
 * Toward white on a dark theme and toward black on a light one, which is the only direction that
 * raises contrast against every surface at once. Monotonic, so a bisection is exact; if even the
 * extreme cannot reach the target the extreme is returned and the audit says so.
 */
function escalate(colour: Rgb, surfaces: readonly Rgb[], target: number, extreme: Rgb): Rgb {
  const worst = (candidate: Rgb): number => Math.min(...surfaces.map((surface) => contrast(candidate, surface)));
  if (worst(colour) >= target) return colour;
  if (worst(extreme) < target) return extreme;
  let low = 0;
  let high = 1;
  for (let step = 0; step < SOLVER_STEPS; step += 1) {
    const middle = (low + high) / HALF;
    if (worst(mix(colour, extreme, middle)) >= target) high = middle;
    else low = middle;
  }
  return mix(colour, extreme, high);
}

/**
 * The four ladder surfaces, re-spaced.
 *
 * Two things have to hold at once and a palette guarantees neither. Each step has to be visible,
 * or hovering a row does nothing. And `hover` — the surface furthest from the canvas, and so the
 * worst case for every foreground tier — has to stay inside the window where `ink` can still reach
 * 10.8:1, or no ink solves. Working in `luminance + flare` makes both statements arithmetic: a
 * contrast ratio between two surfaces is exactly the quotient of their values in that space.
 */
function respaceLadder(seeds: readonly Rgb[], lighter: boolean): Rgb[] {
  const flared = seeds.map((seed) => luminance(seed) + FLARE);
  const first = flared[0] ?? FLARE;
  const values = [first];
  for (let index = 1; index < flared.length; index += 1) {
    const previous = values[index - 1] ?? first;
    const seed = flared[index] ?? previous;
    values.push(lighter ? Math.max(seed, previous * LADDER_STEP) : Math.min(seed, previous / LADDER_STEP));
  }

  // The reachability window: what `hover` may be if pure white (or pure black) is to clear the ink
  // target against it. `ink` is never pure, so the margin buys the palette's own hue some room.
  const limit = lighter
    ? (OPAQUE_WHITE_LUMINANCE + FLARE) / (CONTRAST_TARGET.ink * MARGIN)
    : FLARE * CONTRAST_TARGET.ink * MARGIN;
  const last = values[LADDER_LAST] ?? first;
  if (lighter ? last > limit : last < limit) {
    // Redistribute the whole run geometrically between the fixed canvas and the limit, so the
    // steps stay equal instead of the squeeze landing entirely on the last one.
    const span = limit / first;
    for (let index = 1; index < values.length; index += 1) {
      values[index] = first * Math.pow(span, index / LADDER_LAST);
    }
  }

  return values.map((value, index) => toLuminance(seeds[index] ?? BLACK, value - FLARE));
}

/**
 * Where each verb's colour comes from, in preference order.
 *
 * More than one candidate each because a palette's semantic slots collide constantly: half of them
 * set `primary.base` and `status.info` to the same blue, and Vesper sets four of the six to the
 * same amber. The syntax palette is the second choice everywhere, and it is a good one — making
 * tokens tell each other apart is the entire job of a syntax theme, so its hues are the ones a
 * palette actually spent its variety on.
 */
const METHOD_SOURCES: Record<(typeof METHOD_TOKENS)[number], readonly string[]> = {
  "method-get": ["status.success", "syntax.base.string", "pr.open", "syntax.tokens.method"],
  "method-post": ["status.warning", "syntax.base.number", "pr.blocked", "syntax.tokens.decorator"],
  "method-put": ["primary.base", "syntax.base.function", "status.info", "syntax.tokens.key"],
  "method-patch": ["pr.merged", "syntax.base.keyword", "syntax.tokens.storageModifier", "markdown.blockquote"],
  "method-delete": ["status.error", "syntax.base.operator", "syntax.tokens.exception", "pr.closed"],
  "method-grpc": ["status.info", "syntax.tokens.constant", "syntax.base.type", "markdown.link"],
};

/** Hue rotations tried, in whole turns of this many, when no candidate in the pool is far enough. */
const HUE_STEPS = 36;
const TURN = Math.PI * HALF;
/** Lightness nudges tried when a palette has no hue to rotate — the monochrome case. */
const LIGHTNESS_STEP = 0.03;
const LIGHTNESS_MOVES = 12;
/**
 * How many times the six are swept after the first pass. A greedy assignment is order-dependent —
 * the sixth verb pays for every choice above it — so the run is repeated until nothing moves.
 */
const REPAIR_ROUNDS = 6;

/** OKLab lightness of the extreme a colour is escalated toward; the top of the usable range. */
const LIGHTEST = 1;
const DARKEST = 0;

const NEUTRAL = (lightness: number): Rgb => fromOklch({ l: lightness, c: 0, h: 0 });

/**
 * The band of the OKLab lightness axis a colour can sit in and still clear the method target.
 * Bisected rather than tabulated because it depends on the theme's own canvas and panel.
 *
 * `at` builds the colour under test from a lightness. It defaults to a grey, which is what the
 * monochrome method fallback wants; pass the hue and chroma to hold when placing one token.
 */
function readableBand(readable: (colour: Rgb) => boolean, at: (lightness: number) => Rgb = NEUTRAL): [number, number] {
  const lighter = readable(at(LIGHTEST));
  let inside = lighter ? LIGHTEST : DARKEST;
  let outside = lighter ? DARKEST : LIGHTEST;
  for (let step = 0; step < SOLVER_STEPS; step += 1) {
    const middle = (inside + outside) / HALF;
    if (readable(at(middle))) inside = middle;
    else outside = middle;
  }
  return lighter ? [inside, LIGHTEST] : [DARKEST, inside];
}

/**
 * The four measurements every "these colours must not look alike" solver needs, bound to one
 * theme's surfaces. Extracted because two columns want them: the six verbs, and the template token
 * that has to stay clear of string, number and property.
 */
interface Separator {
  /** Raise a colour until it clears the method contrast target on both surfaces. */
  readonly legible: (colour: Rgb) => Rgb;
  /** Whether it already does. */
  readonly readable: (colour: Rgb) => boolean;
  /** OKLab distance to the nearest colour already taken; infinite when nothing is. */
  readonly spread: (colour: Rgb, taken: readonly Rgb[]) => number;
  /** Every legible move away from a colour, nearest first. */
  readonly moves: (colour: Rgb) => Rgb[];
}

function separator(canvas: Rgb, panel: Rgb, extreme: Rgb): Separator {
  const legible = (colour: Rgb): Rgb => escalate(colour, [canvas, panel], CONTRAST_TARGET.method * MARGIN, extreme);
  const readable = (colour: Rgb): boolean =>
    Math.min(contrast(colour, canvas), contrast(colour, panel)) >= CONTRAST_TARGET.method * MARGIN;
  const spread = (colour: Rgb, taken: readonly Rgb[]): number =>
    taken.length === 0
      ? Number.POSITIVE_INFINITY
      : Math.min(...taken.map((other) => perceptualDistance(colour, other)));

  /**
   * Every way this colour is allowed to move, nearest first: the hue circle in both directions by
   * a widening angle, then lightness in both directions by a widening step. The order is the whole
   * point — the caller takes the first move that clears the threshold, so a verb that only needs a
   * ten degree turn gets a ten degree turn instead of the move that happens to score highest.
   */
  const moves = (colour: Rgb): Rgb[] => {
    const polar = oklch(colour);
    const both = <T>(count: number, at: (signed: number) => T): T[] =>
      Array.from({ length: count }, (_unused, step) => [at(step + 1), at(-(step + 1))]).flat();
    return [
      ...both(HUE_STEPS / HALF, (signed) => fromOklch({ ...polar, h: polar.h + (TURN * signed) / HUE_STEPS })),
      ...both(LIGHTNESS_MOVES, (signed) => fromOklch({ ...polar, l: polar.l + LIGHTNESS_STEP * signed })),
    ].filter(readable);
  };

  return { legible, readable, spread, moves };
}

function dotted(source: Palette["colors"], path: string): string | undefined {
  let node: unknown = source;
  for (const key of path.split(".")) {
    if (typeof node !== "object" || node === null) return undefined;
    node = (node as Record<string, unknown>)[key];
  }
  return typeof node === "string" ? node : undefined;
}

/**
 * The six verb colours, guaranteed to be six colours.
 *
 * The sidebar, the tab strip and the method picker all show the whole set within a few hundred
 * pixels of each other, so two verbs that are the same colour is not a subtle loss — it is a row
 * that lies about what it will send. Read the preferred source, take the next candidate when it
 * collides, and when the palette has run out of hues, move the colour itself: rotate it in OKLCh,
 * which holds the palette's own lightness and saturation, and fall back to lightness for a
 * monochrome palette, where lightness is the only axis it has.
 */
function methodColumn(source: Palette["colors"], canvas: Rgb, panel: Rgb, extreme: Rgb): Record<string, string> {
  const { legible, readable, spread, moves } = separator(canvas, panel, extreme);

  const chosen: Rgb[] = [];
  for (const token of METHOD_TOKENS) {
    const candidates = (METHOD_SOURCES[token] ?? [])
      .map((path) => dotted(source, path))
      .filter((value): value is string => value !== undefined)
      .map((value) => legible(flatten(parseColor(value), canvas)));
    const preferred = candidates[0] ?? legible(canvas);
    chosen.push(
      candidates.find((candidate) => spread(candidate, chosen) >= METHOD_MIN_DISTANCE) ??
        candidates.reduce(
          (best, candidate) => (spread(candidate, chosen) > spread(best, chosen) ? candidate : best),
          preferred,
        ),
    );
  }

  for (let round = 0; round < REPAIR_ROUNDS; round += 1) {
    let moved = false;
    for (const [index, colour] of chosen.entries()) {
      const others = chosen.filter((_unused, other) => other !== index);
      if (spread(colour, others) >= METHOD_MIN_DISTANCE) continue;
      const candidates = moves(colour);
      const improved =
        candidates.find((candidate) => spread(candidate, others) >= METHOD_MIN_DISTANCE) ??
        candidates.reduce(
          (best, candidate) => (spread(candidate, others) > spread(best, others) ? candidate : best),
          colour,
        );
      if (improved === colour) continue;
      chosen[index] = improved;
      moved = true;
    }
    if (!moved) break;
  }

  // The monochrome case. A palette with no chroma has nothing for a hue rotation to turn, so the
  // only axis left is the one it does have: spread all six evenly up the readable lightness range,
  // in the order they already sit in. Ranking rather than reassigning keeps GET lighter than POST
  // if that is how the palette had it, and the even spacing is what the pairwise rule asks for.
  const others = (index: number): Rgb[] => chosen.filter((_unused, other) => other !== index);
  if (chosen.some((colour, index) => spread(colour, others(index)) < METHOD_MIN_DISTANCE)) {
    const [low, high] = readableBand(readable);
    const rank = chosen.map((colour, index) => ({ index, l: oklch(colour).l })).sort((a, b) => a.l - b.l);
    for (const [position, entry] of rank.entries()) {
      const polar = oklch(chosen[entry.index] ?? canvas);
      const share = position / (METHOD_TOKENS.length - 1);
      chosen[entry.index] = fromOklch({ ...polar, l: low + (high - low) * share });
    }
  }

  return Object.fromEntries(METHOD_TOKENS.map((token, index) => [token, toHex(chosen[index] ?? canvas)]));
}

/**
 * Where to look for `--syntax-template`, in order of preference.
 *
 * A `{{token}}` is not a language construct, so no palette has a slot for it. What it *is* is the
 * one span in a request body that will be something else by the time it is sent, which is the same
 * job a macro or a decorator does in a language: a marker that this text is about to be replaced.
 * Those are the slots a palette is most likely to have spent a distinct hue on, and the ones a
 * reader already reads as "not literal".
 */
const TEMPLATE_SOURCES: readonly string[] = [
  "syntax.tokens.macro",
  "syntax.tokens.decorator",
  "syntax.base.variable",
  "markdown.inlineCode",
  "status.info",
  "pr.draft",
];

/**
 * The one colour that has to stand apart from three specific others.
 *
 * A token appears exactly where a string or a number would, often on the same line as both, and
 * every key around it is `property` — so unlike the method column, whose members only have to
 * differ from each other, this one has three fixed neighbours it must clear and no say in where
 * they sit. Measured, not assumed: four of the vendored palettes give `macro` and `property` the
 * same hex, so reading the preferred source and stopping would have shipped a token that is
 * invisible as a token in those four.
 */
function templateColour(
  source: Palette["colors"],
  neighbours: readonly Rgb[],
  canvas: Rgb,
  panel: Rgb,
  extreme: Rgb,
): string {
  const { legible, readable, spread, moves } = separator(canvas, panel, extreme);
  const clear = (colour: Rgb): boolean => spread(colour, neighbours) >= TEMPLATE_MIN_DISTANCE;
  const furthest = (from: Rgb, pool: readonly Rgb[]): Rgb =>
    pool.reduce(
      (best, candidate) => (spread(candidate, neighbours) > spread(best, neighbours) ? candidate : best),
      from,
    );

  const candidates = TEMPLATE_SOURCES.map((path) => dotted(source, path))
    .filter((value): value is string => value !== undefined)
    .map((value) => legible(flatten(parseColor(value), canvas)));
  const preferred = candidates[0] ?? legible(canvas);
  const usable = candidates.find(clear);
  if (usable !== undefined) return toHex(usable);

  // Nothing in the palette is far enough from all three. Rotate instead: the nearest legible turn
  // of the hue circle that clears the gap, which holds the palette's own lightness.
  const rotated = moves(preferred);
  const turned = rotated.find(clear);
  if (turned !== undefined) return toHex(turned);

  // A monochrome palette has no hue to turn, and its lightness axis is already crowded — mono-dark
  // puts number, string and property at 0.68, 0.77 and 0.92, and pins the floor at 0.58. On one
  // axis the best position is always an end of the readable band or the middle of a gap between two
  // neighbours, so solve for those exactly rather than sweeping a grid: the grid's 0.03 step misses
  // the floor by 0.01 and loses a gap that is actually there.
  const polar = oklch(preferred);
  const at = (lightness: number): Rgb => fromOklch({ ...polar, l: lightness });
  const [low, high] = readableBand(readable, at);
  const inside = neighbours
    .map((neighbour) => oklch(neighbour).l)
    .filter((lightness) => lightness > low && lightness < high)
    .sort((a, b) => a - b);
  const edges = [low, ...inside, high];
  const places = [low, high, ...edges.slice(1).map((edge, index) => ((edges[index] ?? low) + edge) / HALF)];

  return toHex(furthest(preferred, [...places.map(at), ...rotated]));
}

function shadowFor(canvas: Rgb, lighter: boolean): string {
  const recipe = lighter ? SHADOW.dark : SHADOW.light;
  const tinted = mix(canvas, BLACK, recipe.toward);
  const channel = (value: number): number => Math.round(value);
  return `${SHADOW_GEOMETRY} rgb(${channel(tinted.r)} ${channel(tinted.g)} ${channel(tinted.b)} / ${recipe.alpha.toFixed(ALPHA_DECIMALS)})`;
}

function familyOf(id: string): string {
  const known = Object.keys(ATTRIBUTION)
    .filter((family) => id === family || id.startsWith(`${family}-`))
    .sort((a, b) => b.length - a.length);
  const best = known[0];
  if (best === undefined) throw new Error(`no attribution for ${id}`);
  return best;
}

