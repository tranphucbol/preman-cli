/**
 * Turn the vendored palettes into audited theme modules. Run by hand:
 *
 *   bun run packages/desktop/scripts/generate-themes.ts
 *
 * By hand, and not as a build step, for the same reason `resources/generate.swift` is: a build
 * step nobody inspects the output of is a build step that hides a bad colour. The output is
 * committed, so a reviewer sees the hex that changed rather than a script that changed.
 *
 * It lives outside `src/renderer/` because it needs `node:fs` and the renderer fence forbids
 * `node:*` there. Its output is pure data and belongs inside.
 *
 * Three of the twenty-one colours are *solved*, not read: `ink-dim`, `ink-faint` and `glyph` have
 * no source field, and are faded from `ink` toward `canvas` until the measured worst case against
 * all five surfaces lands on the target. That is the whole point of generating rather than
 * transcribing — the contrast contract in `app.css` stops being a comment describing one palette
 * and becomes a property that holds for every palette.
 *
 * `config.fonts` in the source is dropped, deliberately. One Dark Pro's `sans` is a *monospace*
 * stack, so importing it would mean picking a theme silently changed the UI's typeface. Theme is
 * colour, font is font; they travel together in someone else's file format and that is not a
 * reason to couple them here.
 */
