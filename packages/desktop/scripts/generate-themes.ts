function convert(palette: Palette, overrides: Overrides): Generated {
  const { metadata } = palette;
  const id = metadata.id;
  const lighter = metadata.variant === "dark";
  const extreme = lighter ? WHITE : BLACK;
  const source = palette.colors;
  const surfaceOf = (key: string): string => read(source.surface, key, `${id}.surface`);

  const canvasSeed = opaque(surfaceOf("background"), BLACK);
  const seeds = [
    canvasSeed,
    opaque(surfaceOf("muted"), canvasSeed),
    opaque(surfaceOf("elevated"), canvasSeed),
    opaque(surfaceOf("subtle"), canvasSeed),
  ];
  const [canvas = canvasSeed, panel = canvasSeed, control = canvasSeed, hover = canvasSeed] = respaceLadder(
    seeds,
    lighter,
  );

  const accentSeed = opaque(read(source.primary, "base", `${id}.primary`), canvas);
  const accent = escalate(accentSeed, [canvas, panel], CONTRAST_TARGET.accentForeground * MARGIN, extreme);

  // `interactive.selection` is an overlay in the source, and preman's selected row is a solid fill.
  // Flatten it, pull it toward the accent, then put it back on `hover`'s luminance: the whole rule
  // is that selection is a *tint* at hover brightness, so every ink tier stays legible on it.
  const selected = toLuminance(
    mix(opaque(read(source.interactive, "selection", `${id}.interactive`), canvas), accent, SELECTION_TINT),
    luminance(hover),
  );

  const surfaces = [canvas, panel, control, hover, selected];
  const ink = escalate(opaque(surfaceOf("foreground"), canvas), surfaces, CONTRAST_TARGET.ink * MARGIN, extreme);
  const fade = (target: number): Rgb => fadeToTarget(ink, canvas, surfaces, target * MARGIN);

  const status = (key: string): Rgb =>
    escalate(
      opaque(read(source.status, key, `${id}.status`), canvas),
      [canvas, panel],
      CONTRAST_TARGET.method * MARGIN,
      extreme,
    );

  const colors: Record<string, string> = {
    canvas: toHex(canvas),
    panel: toHex(panel),
    control: toHex(control),
    hover: toHex(hover),
    selected: toHex(selected),
    line: toHex(opaque(read(source.interactive, "border", `${id}.interactive`), panel)),
    "line-strong": toHex(opaque(read(source.interactive, "borderHover", `${id}.interactive`), panel)),
    ink: toHex(ink),
    "ink-dim": toHex(fade(CONTRAST_TARGET.inkDim)),
    "ink-faint": toHex(fade(CONTRAST_TARGET.inkFaint)),
    glyph: toHex(fade(CONTRAST_TARGET.glyph)),
    accent: toHex(accent),
    ok: toHex(status("success")),
    warn: toHex(status("warning")),
    danger: toHex(status("error")),
    ...methodColumn(source, canvas, panel, extreme),
    ...(overrides[id]?.colors ?? {}),
  };

  const syntaxOf = (group: string, key: string): string | undefined => {
    if (group === "base") return source.syntax.base[key];
    if (group === "tokens") return source.syntax.tokens[key];
    return source.syntax.highlights[key];
  };
  const syntax: Record<string, string> = {};
  for (const [token, { from, or }] of Object.entries(SYNTAX_SOURCES)) {
    const raw = syntaxOf(from[0], from[1]) ?? (or === undefined ? undefined : syntaxOf(or[0], or[1]));
    if (raw === undefined) throw new Error(`${id} has no source for --syntax-${token}`);
    syntax[token] = toHex(escalate(opaque(raw, panel), [canvas, panel], CONTRAST_TARGET.method * MARGIN, extreme));
  }
  const elsewhere: Record<(typeof SYNTAX_ELSEWHERE)[number], string> = {
    invalid: read(source.status, "error", `${id}.status`),
    heading: read(source.markdown, "heading1", `${id}.markdown`),
    link: read(source.markdown, "link", `${id}.markdown`),
  };
  for (const token of SYNTAX_ELSEWHERE) {
    syntax[token] = toHex(
      escalate(opaque(elsewhere[token], panel), [canvas, panel], CONTRAST_TARGET.method * MARGIN, extreme),
    );
  }

  // Last, because it is solved against the three tokens above rather than read from a slot.
  const neighbours = TEMPLATE_NEIGHBOURS.map((token) => {
    const hex = syntax[token];
    if (hex === undefined) throw new Error(`${id} has no --syntax-${token} to separate the template token from`);
    return parseColor(hex);
  });
  syntax.template = templateColour(source, neighbours, canvas, panel, extreme);

  Object.assign(syntax, overrides[id]?.syntax ?? {});

  const attribution = ATTRIBUTION[familyOf(id)];
  if (attribution === undefined) throw new Error(`no attribution for ${id}`);

  return {
    id,
    name: metadata.name,
    variant: lighter ? "dark" : "light",
    source: attribution.source,
    licence: attribution.licence,
    colors,
    syntax,
    shadowFloat: shadowFor(canvas, lighter),
  };
}

function identifierFor(id: string): string {
  return id.replace(/-([a-z0-9])/g, (_match, character: string) => character.toUpperCase());
}

function serialise(theme: Generated): string {
  const entries = (record: Readonly<Record<string, string>>): string =>
    Object.entries(record)
      .map(([token, value]) => `    ${JSON.stringify(token)}: ${JSON.stringify(value)},`)
      .join("\n");
  return `${HEADER}
import type { Theme } from "@preman/desktop/renderer/appearance/theme.js";

export const ${identifierFor(theme.id)}: Theme = {
  id: ${JSON.stringify(theme.id)},
  name: ${JSON.stringify(theme.name)},
  variant: ${JSON.stringify(theme.variant)},
  source: ${JSON.stringify(theme.source)},
  licence: ${JSON.stringify(theme.licence)},
  colors: {
${entries(theme.colors)}
  },
  syntax: {
${entries(theme.syntax)}
  },
  shadowFloat: ${JSON.stringify(theme.shadowFloat)},
};
`;
}

/**
 * One module with static imports, and no lazy split.
 *
 * Forty-three themes of about fifty-six values each is roughly 2,400 hex strings, which V8 parses
 * in single-digit milliseconds. A lazy body would save a few of those and make a theme change
 * `async`, which then has to interact with the apply-before-first-paint path.
 */
function serialiseIndex(ids: readonly string[]): string {
  const imports = ids.map((id) => `import { ${identifierFor(id)} } from "./${id}.js";`).join("\n");
  return `${HEADER}
import type { Theme } from "@preman/desktop/renderer/appearance/theme.js";
${imports}

/** Every bundled theme, ${JSON.stringify(HAND_WRITTEN)} first because it is the default. */
export const THEMES: readonly Theme[] = [${ids.map(identifierFor).join(", ")}];
`;
}

/**
 * The output is committed, so it is held to the same formatting as anything else in the tree —
 * `format:check` does not know a file was written by a script. Running Prettier here, rather than
 * ignoring the directory, keeps the generated modules and the hand-written `preman-dark.ts` beside
 * them under one rule.
 */
async function write(file: string, source: string): Promise<void> {
  const options = await resolveConfig(file);
  writeFileSync(file, await format(source, { ...options, filepath: file }), ENCODING);
}

async function main(): Promise<void> {
  const overrides: Overrides = JSON.parse(readFileSync(OVERRIDE_FILE, ENCODING)) as Overrides;
  const files = readdirSync(PALETTE_DIR)
    .filter((file) => file.endsWith(JSON_EXTENSION) && file !== "overrides.json")
    .sort();

  const generated: Generated[] = [];
  for (const file of files) {
    const palette = JSON.parse(readFileSync(join(PALETTE_DIR, file), ENCODING)) as Palette;
    generated.push(convert(palette, overrides));
  }

  let failed = 0;
  for (const theme of generated) {
    const violations = auditTheme(theme);
    if (violations.length === 0) continue;
    failed += 1;
    process.stdout.write(`${theme.id}\n${violations.map((line) => `  ${line}`).join("\n")}\n`);
  }

  for (const theme of generated) {
    await write(join(OUTPUT_DIR, `${theme.id}.ts`), serialise(theme));
  }
  await write(join(OUTPUT_DIR, "index.ts"), serialiseIndex([HAND_WRITTEN, ...generated.map((theme) => theme.id)]));

  process.stdout.write(
    `${String(generated.length)} palettes converted, ${String(failed)} with violations, ` +
      `${String(SURFACE_MIN_STEP)} minimum ladder step, ${String(METHOD_TOKENS.length)} method colours each\n`,
  );
  if (failed > 0) process.exitCode = EXIT_FAILURE;
}

await main();
